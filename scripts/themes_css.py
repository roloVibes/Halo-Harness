"""scripts/themes_css.py -- write Studio's palette blocks into styles/tokens.css from the palette registry
(Halo 3.3.12.0 R1; halo_harness/themes).

    python scripts/themes_css.py           rewrite the block between the two marker comments of tokens.css
    python scripts/themes_css.py --check   exit 1 when the block differs from what the registry renders

One `:root[data-theme="<name>"]` rule per palette (the palette's own id and its `-ansi` name: a browser always
draws full colour), one override rule per `-daltonized` name (only the variables it changes), and "follow the
system" (`data-theme="auto"`, the default): holo, or paper inside `@media (prefers-color-scheme: light)`. `:root`
alone is holo too, so a page with no attribute is drawn as before. Studio's derived variables (the glass, the
lines, the glows, the soft fills, the scrim) come from the tokens by the posture's rule below, so a colour lives
in halo_harness/themes/palettes.py and nowhere else. tests/test_themes_css_drift.py runs `--check`.
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

TOKENS_CSS = REPO / "halo_harness" / "studio" / "ui" / "src" / "styles" / "tokens.css"
BEGIN = "/* themes:begin -- generated by scripts/themes_css.py from halo_harness/themes/palettes.py; edit those, not this */"
END = "/* themes:end */"
WIDTH = 118

# The posture's rule for every variable Studio derives: (alpha of each soft fill, the glass, lines, glows, scrim).
SOFT = {"dark": {"accent": "0.14", "warn": "0.16", "bad": "0.16", "ok": "0.14"},
        "light": {"accent": "0.10", "warn": "0.14", "bad": "0.10", "ok": "0.12"}}
SCRIM_DARK = "rgba(2, 5, 12, 0.62)"


def rgba(hexstr: str, alpha: str) -> str:
    from halo_harness.themes.registry import rgb
    r, g, b = rgb(hexstr)
    return f"rgba({r}, {g}, {b}, {alpha})"


def accent_vars(t: dict, posture: str) -> list:
    """The variables that follow the accent and status pair (all a -daltonized rule needs to restate)."""
    a, soft = t["accent"], SOFT[posture]
    if posture == "dark":
        glow = f"0 0 0 1px {rgba(a, '0.10')}, 0 8px 32px rgba(0, 0, 0, 0.45), 0 0 24px {rgba(a, '0.06')}"
        strong = f"0 0 0 1px {rgba(a, '0.35')}, 0 0 28px {rgba(a, '0.22')}"
    else:
        glow = f"0 1px 0 {rgba(t['text'], '0.04')}, 0 8px 24px {rgba(t['text'], '0.12')}"
        strong = f"0 0 0 1px {rgba(a, '0.45')}, 0 6px 20px {rgba(a, '0.16')}"
    return [("--glow", glow), ("--glow-strong", strong), ("--accent", a), ("--accent-2", t["accent2"]),
            ("--accent-ink", t["accent_ink"]), ("--accent-soft", rgba(a, soft["accent"])), ("--ok", t["ok"]),
            ("--ok-soft", rgba(t["ok"], soft["ok"])), ("--warn", t["warn"]), ("--warn-soft", rgba(t["warn"], soft["warn"])),
            ("--bad", t["bad"]), ("--bad-soft", rgba(t["bad"], soft["bad"]))]


def studio_vars(t: dict, posture: str) -> list:
    """Every colour variable of styles/tokens.css for a palette's tokens, in one order."""
    dark = posture == "dark"
    out = [("color-scheme", posture), ("--bg", t["bg"]), ("--bg-2", t["bg2"]), ("--surface", t["surface"]),
           ("--surface-2", t["surface2"]), ("--surface-glass", rgba(t["surface"], "0.72" if dark else "0.82")),
           ("--line", rgba(t["line"], "0.16") if dark else t["line"]),
           ("--line-strong", rgba(t["line"], "0.34") if dark else t["faint"]),
           ("--grid-line", rgba(t["line"], "0.045") if dark else rgba(t["text"], "0.06"))]
    out += accent_vars(t, posture)
    out += [("--text", t["text"]), ("--muted", t["muted"]), ("--faint", t["faint"]),
            ("--scrim", SCRIM_DARK if dark else rgba(t["text"], "0.30")), ("--bracket-alpha", "0.55" if dark else "0")]
    return out


def rule(selectors: list, decls: list, indent: str = "") -> list:
    """A rule with its declarations packed onto as few lines as fit WIDTH (tokens.css stays under 250 lines)."""
    lines, cur = [indent + ", ".join(selectors) + " {"], indent + " "
    for name, value in decls:
        piece = f" {name}: {value};"
        if len(cur) + len(piece) > WIDTH and cur.strip():
            lines.append(cur)
            cur = indent + " "
        cur += piece
    if cur.strip():
        lines.append(cur)
    return lines + [indent + "}"]


def _sel(name: str) -> str:
    return f':root[data-theme="{name}"]'


def render() -> str:
    from halo_harness.themes.palettes import FOLLOW_DARK, FOLLOW_LIGHT, PALETTES
    from halo_harness.themes.registry import daltonize
    out = [BEGIN]
    for p in PALETTES:
        sels = [_sel(p["id"]), _sel(p["id"] + "-daltonized"), _sel(p["id"] + "-ansi")]
        if p["id"] == FOLLOW_DARK:
            sels = [":root"] + sels + [_sel("auto")]
        out += rule(sels, studio_vars(p["tokens"], p["posture"]))
    for p in PALETTES:
        base = dict(accent_vars(p["tokens"], p["posture"]))
        changed = [(k, v) for k, v in accent_vars(daltonize(p["tokens"], p["posture"]), p["posture"]) if base.get(k) != v]
        out += rule([_sel(p["id"] + "-daltonized")], changed)
    light = next(p for p in PALETTES if p["id"] == FOLLOW_LIGHT)
    out += ["@media (prefers-color-scheme: light) {"] + rule([_sel("auto")], studio_vars(light["tokens"], "light"), "  ") + ["}"]
    return "\n".join(out + [END])


def spliced(css: str) -> str:
    head, sep, rest = css.partition(BEGIN)
    _old, sep2, tail = rest.partition(END)
    if not sep or not sep2:
        raise SystemExit(f"themes_css: {TOKENS_CSS.name} has no {BEGIN[:16]} ... {END} markers")
    return head + render() + tail


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    css = TOKENS_CSS.read_text(encoding="utf-8")
    want = spliced(css)
    if "--check" in argv:
        if want != css:
            print(f"themes_css: {TOKENS_CSS.relative_to(REPO).as_posix()} drifted from the registry; run python scripts/themes_css.py")
            return 1
        print("themes_css: tokens.css matches the registry")
        return 0
    if want != css:
        TOKENS_CSS.write_text(want, encoding="utf-8", newline="\n")
        print(f"themes_css: wrote {TOKENS_CSS.relative_to(REPO).as_posix()}")
    else:
        print("themes_css: tokens.css already matches the registry")
    return 0


if __name__ == "__main__":
    sys.exit(main())
