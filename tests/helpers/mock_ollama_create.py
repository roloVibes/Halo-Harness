"""tests.helpers.mock_ollama_create -- Halo 3.2.3.0 R3: the mock Ollama's
derived-model `/api/create` (`{"model", "from", "parameters"}`) and
`DELETE /api/delete`, the way the real daemon answers them: the new model
joins `/api/tags` and `/api/show`, its `/api/show` carries the original's
`model_info` / `details` with `details.parent_model` = the `from` model
(unless `mock.create_records_parent` is False: an older server) and the
merged `parameters` text in Ollama's own `name<padding>value` lines.
"""

from __future__ import annotations

import json

CREATE_FROM_LINES = [{"status": "using existing layer sha256:aaaa"}, {"status": "creating new layer sha256:bbbb"},
                     {"status": "writing manifest"}, {"status": "success"}]


def _norm(name: str) -> str:
    name = (name or "").strip()
    return name if ":" in name.rsplit("/", 1)[-1] else f"{name}:latest"


def _lookup(table: dict, name: str):
    for key in (name, _norm(name)):
        if key in table:
            return key, table[key]
    return None, None


def _param_lines(params: dict) -> str:
    lines = []
    for k, v in params.items():
        value = json.dumps(v) if isinstance(v, str) else str(v)
        lines.append(f"{k:<30} {value}")
    return "\n".join(lines)


def _parse_params(text: str) -> dict:
    out: dict = {}
    for line in (text or "").splitlines():
        parts = line.split(None, 1)
        if len(parts) == 2:
            raw = parts[1].strip()
            try:
                out[parts[0]] = json.loads(raw)
            except ValueError:
                out[parts[0]] = raw
    return out


def apply_create(mock, body: dict) -> list:
    """The NDJSON lines for a `from` create, after adding the model."""
    name = _norm((body or {}).get("model") or "")
    source = (body or {}).get("from") or ""
    with mock._lock:
        key, show = _lookup(mock.show_responses, source)
        if show is None:
            return [{"status": "parsing modelfile"}, {"error": f"model '{source}' not found"}]
        merged = _parse_params(show.get("parameters") or "")
        merged.update((body or {}).get("parameters") or {})
        new_show = json.loads(json.dumps(show))
        details = dict(new_show.get("details") or {})
        details["parent_model"] = key if getattr(mock, "create_records_parent", True) else ""
        new_show["details"] = details
        new_show["parameters"] = _param_lines(merged)
        new_show["modelfile"] = ("# Modelfile generated by \"ollama show\"\nFROM /blobs/sha256-aaaa\n"
                                 + "".join(f"PARAMETER {k} {v}\n" for k, v in merged.items()))
        mock.show_responses[name] = new_show
        tags = mock.tags_response.setdefault("models", [])
        base = next((t for t in tags if _norm(t.get("model") or t.get("name") or "") == _norm(source)), {})
        tags[:] = [t for t in tags if _norm(t.get("model") or t.get("name") or "") != name]
        row = json.loads(json.dumps(base)) if base else {"size": 1}
        row.update({"name": name, "model": name, "digest": f"sha256:twin{len(tags)}"})
        tags.append(row)
        mock.created.append(dict(body or {}))
    return list(getattr(mock, "create_from_lines", None) or CREATE_FROM_LINES)


def apply_delete(mock, body: dict) -> "tuple[int, dict]":
    name = (body or {}).get("model") or ""
    with mock._lock:
        key, show = _lookup(mock.show_responses, name)
        if show is None:
            return 404, {"error": f"model '{name}' not found"}
        del mock.show_responses[key]
        tags = mock.tags_response.get("models") or []
        tags[:] = [t for t in tags if _norm(t.get("model") or t.get("name") or "") != _norm(name)]
        mock.deleted.append(name)
    return 200, {}
